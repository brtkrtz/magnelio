# Glyphs are sized so a full-length arrow spans this fraction of the
# monitor's bounding-box diagonal.
_GLYPH_LENGTH_FRACTION = 1.0 / 25.0
# Spatial samples used when estimating the magnitude statistics.
_CAP_MAX_SAMPLES = 1_500_000
_CAP_TIME_SAMPLES = 6
# Cells below this fraction of the peak magnitude do not count towards the
# length reference (PEC interiors, quiet volume).
_LIVE_CELL_FRACTION = 0.01
# Percentile of the field-carrying cells taken as the typical magnitude.
_REFERENCE_PERCENTILE = 60.0
# ... which is drawn at this fraction of the full arrow length.  Fixing
# the pair (reference -> this fraction, cap -> full length) is what the
# glyph length exponent is fitted to.
_REFERENCE_LENGTH_FRACTION = 0.45
_EXPONENT_LIMITS = (0.2, 1.0)
# Volume glyphs drop cells below this fraction of the cap: a whole-domain
# monitor is mostly PEC interior and quiet volume, and filling those with
# short arrows buries the field.  Slice glyphs keep every cell — on a
# single cut the empty regions read as information, not clutter.
_VOLUME_THRESHOLD_FRACTION = 0.02
# Arrows are always placed on an evenly spaced lattice (DD-115 follow-up),
# never on the computational grid.  Two lattices per 3D monitor, because
# the two views need different densities: a cut wants arrows per unit
# AREA, a volume view a bounded total count.
_ARROWS_PER_SECTION = 2000
_RESAMPLE_VOLUME_POINTS = 8000
_RESAMPLE_MAX_PER_AXIS = 300

#: Component axis behind a field-array suffix (``Ey`` -> 1).
_COMP_AXES = {"x": 0, "y": 1, "z": 2}

#: Printed by the session script after it saves a state file, and read
#: back by :func:`bake_pvsm`: a ``.pvsm`` is bound to the ParaView that
#: wrote it (proxy names change between releases), so the version goes
#: into the script's header where a later reader can find it.
_VERSION_MARKER = "MAGNELIO_PARAVIEW_VERSION"


def _sanitize(name: str) -> str:
    """File-system-safe token for a monitor / block name."""
    return re.sub(r"[^\w.-]+", "_", name).strip("_") or "unnamed"


def _material_table(materials, colors=None) -> tuple[list[dict], list[int]]:
    """Unique material table and the per-shape index into it.

    Deterministic for a given shape order, so the ``MaterialIndex`` cell
    array written by :func:`export_vtm` and the lookup table generated by
    :func:`export_run_visualization` (which re-derives the table from
    ``geometry.json``) always agree.

    *colors* optionally carries the per-shape display colour imported
    from a CAD file, so two shapes of the same material but different
    file colours become two entries.
    """
    from magnelio.post._colors import material_color  # noqa: PLC0415

    table: list[dict] = []
    index_of: dict = {}
    used_names: set[str] = set()
    indices = []
    if colors is None:
        colors = [None] * len(materials)
    for mat, color in zip(materials, colors):
        rgba = tuple(round(float(c), 6) for c in material_color(mat, color))
        if rgba[3] == 0.0 and getattr(mat, "color", None) is None and getattr(mat, "visible", True):
            # Auto-coloured air/vacuum: the 2D cross-sections draw it as
            # a dashed wall outline, but in 3D the vacuum volume IS the
            # device (a cavity carved into metal) — render it as a light
            # translucent blue instead of not at all.  An explicit
            # Material(color=..., alpha=...) or visible=False still wins.
            rgba = (0.25, 0.5, 1.0, 0.3)
        name = getattr(mat, "name", None) or "material"
        key = (name, rgba)
        if key not in index_of:
            label = name
            n = 2
            while label in used_names:
                label = f"{name} #{n}"
                n += 1
            used_names.add(label)
            index_of[key] = len(table)
            table.append({"name": label, "rgba": list(rgba)})
        indices.append(index_of[key])
    return table, indices


