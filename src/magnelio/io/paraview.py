# OCC rejects a linear deflection below ``Precision::Confusion()`` (1e-7
# in the kernel's units) with a Standard_NumericError; a body of a few
# tens of micrometres at metre scale asks for less, so every deflection
# handed to ``BRepMesh_IncrementalMesh`` is floored here.
_OCC_MIN_DEFLECTION = 1.1e-7


def _occ_deflection(shape, rel: float) -> float:
    """Linear deflection as a fraction of the shape's bbox diagonal."""
    from OCC.Core.Bnd import Bnd_Box  # noqa: PLC0415

    try:
        from OCC.Core.BRepBndLib import brepbndlib  # noqa: PLC0415

        add = brepbndlib.Add
    except ImportError:  # pragma: no cover - legacy pythonocc naming
        from OCC.Core.BRepBndLib import brepbndlib_Add as add  # noqa: PLC0415

    box = Bnd_Box()
    add(shape, box)
    if box.IsVoid():
        return 1e-4
    xmin, ymin, zmin, xmax, ymax, zmax = box.Get()
    diag = float(np.sqrt((xmax - xmin) ** 2 + (ymax - ymin) ** 2 + (zmax - zmin) ** 2))
    return max(rel * diag, _OCC_MIN_DEFLECTION)


def _tessellate_shape(occ_shape, deflection: float | None, angular_deflection: float = 0.5):
    """Triangulate one TopoDS shape into ``(points, triangles)`` arrays.

    Returns ``None`` when the shape yields no triangulation (e.g. an
    empty compound).  Face orientation is honoured so outward normals
    survive into the ``.vtp`` blocks.  ``angular_deflection`` [rad]
    bounds the angle between neighbouring facets on curved faces (the
    OCC default 0.5 leaves visible facets on cylinders).
    """
    from OCC.Core.BRep import BRep_Tool  # noqa: PLC0415
    from OCC.Core.BRepMesh import BRepMesh_IncrementalMesh  # noqa: PLC0415
    from OCC.Core.TopAbs import TopAbs_FACE, TopAbs_REVERSED  # noqa: PLC0415
    from OCC.Core.TopExp import TopExp_Explorer  # noqa: PLC0415
    from OCC.Core.TopLoc import TopLoc_Location  # noqa: PLC0415
    from OCC.Core.TopoDS import topods  # noqa: PLC0415

    defl = deflection if deflection is not None else _occ_deflection(occ_shape, 2e-3)
    defl = max(float(defl), _OCC_MIN_DEFLECTION)
    BRepMesh_IncrementalMesh(occ_shape, defl, False, angular_deflection, True)

    points: list[np.ndarray] = []
    tris: list[np.ndarray] = []
    offset = 0
    exp = TopExp_Explorer(occ_shape, TopAbs_FACE)
    while exp.More():
        face = topods.Face(exp.Current())
        exp.Next()
        loc = TopLoc_Location()
        tri = BRep_Tool.Triangulation(face, loc)
        if tri is None:
            continue
        trsf = loc.Transformation()
        n_nodes = tri.NbNodes()
        pts = np.empty((n_nodes, 3), dtype=np.float64)
        for i in range(1, n_nodes + 1):
            p = tri.Node(i).Transformed(trsf)
            pts[i - 1] = (p.X(), p.Y(), p.Z())
        n_tri = tri.NbTriangles()
        con = np.empty((n_tri, 3), dtype=np.int64)
        reversed_face = face.Orientation() == TopAbs_REVERSED
        for i in range(1, n_tri + 1):
            a, b, c = tri.Triangle(i).Get()
            con[i - 1] = (c, b, a) if reversed_face else (a, b, c)
        points.append(pts)
        tris.append(con - 1 + offset)
        offset += n_nodes
    if not points:
        return None
    return np.vstack(points), np.vstack(tris)


def _polydata(points: np.ndarray, triangles: np.ndarray):
    """Build a ``vtkPolyData`` from point / triangle index arrays."""
    import vtk  # noqa: PLC0415
    from vtk.util import numpy_support as ns  # noqa: PLC0415

    pd = vtk.vtkPolyData()
    vpts = vtk.vtkPoints()
    vpts.SetData(ns.numpy_to_vtk(np.ascontiguousarray(points), deep=True))
    pd.SetPoints(vpts)
    n_tri = triangles.shape[0]
    offsets = np.arange(0, 3 * (n_tri + 1), 3, dtype=np.int64)
    conn = np.ascontiguousarray(triangles, dtype=np.int64).ravel()
    ca = vtk.vtkCellArray()
    ca.SetData(
        ns.numpy_to_vtkIdTypeArray(offsets, deep=True),
        ns.numpy_to_vtkIdTypeArray(conn, deep=True),
    )
    pd.SetPolys(ca)
    return pd


def _half_and_mirror(pd, axis: int, wall: float, at_low: bool):
    """Clip *pd* to the simulated half and append its reflection (DD-265).

    The solids of a model behind symmetry planes are stored as the half
    the solver saw; ParaView used to complete them with its own
    ``Reflect`` filter, whose proxy name changed between releases and
    took the whole geometry branch of a baked state down with it.  The
    completion happens here instead, in this process's VTK, so the
    session only ever reads a whole model.

    A mirror reverses the winding of every triangle, so the reflected
    copy is passed through ``vtkReverseSense``; without it the solids
    would be lit from inside.
    """
    import vtk  # noqa: PLC0415

    origin = [0.0, 0.0, 0.0]
    origin[axis] = wall
    normal = [0.0, 0.0, 0.0]
    normal[axis] = 1.0
    plane = vtk.vtkPlane()
    plane.SetOrigin(origin)
    plane.SetNormal(normal)

    clip = vtk.vtkClipPolyData()
    clip.SetInputData(pd)
    clip.SetClipFunction(plane)
    # The wall at the low end leaves the model on the positive side.
    clip.SetInsideOut(0 if at_low else 1)
    clip.Update()
    half = clip.GetOutput()
    if half.GetNumberOfCells() == 0:
        return pd

    transform = vtk.vtkTransform()
    shift = [0.0, 0.0, 0.0]
    shift[axis] = 2.0 * wall
    scale = [1.0, 1.0, 1.0]
    scale[axis] = -1.0
    # Pre-multiplied: the scale acts first, so x -> 2*wall - x.
    transform.Translate(*shift)
    transform.Scale(*scale)
    mirrored = vtk.vtkTransformPolyDataFilter()
    mirrored.SetInputData(half)
    mirrored.SetTransform(transform)
    flip = vtk.vtkReverseSense()
    flip.SetInputConnection(mirrored.GetOutputPort())
    flip.ReverseCellsOn()
    flip.ReverseNormalsOn()

    append = vtk.vtkAppendPolyData()
    append.AddInputData(half)
    append.AddInputConnection(flip.GetOutputPort())
    append.Update()
    return append.GetOutput()


def export_vtm(
    path: str | Path,
    geometry,
    deflection: float | None = None,
    mirrors=None,
) -> list[dict]:
    """Export solids as a per-solid VTK multiblock dataset (``.vtm``).

    Each solid becomes its own named block carrying a constant
    ``MaterialIndex`` cell array (index into the returned material table)
    and the material name as field data, so ParaView can colour blocks
    per material with a categorical lookup table and users can hide or
    extract individual solids.

    Parameters
    ----------
    path : str or Path
        Output file path (``.vtm``; a sibling data directory is created).
    geometry : iterable
        Shape objects exposing ``_occ_shape()`` and ``material`` —
        a :class:`~magnelio.geo.GeometryModel`, a
        :class:`~magnelio.io.project.LoadedGeometry`, or a plain list.
        Thin wires must be filtered out by the caller.
    deflection : float, optional
        Absolute tessellation accuracy [m].  Default: 0.2 % of each
        solid's bounding-box diagonal (scale-independent).
    mirrors : sequence, optional
        Declared symmetry planes as ``(axis, wall [m], at_low, kind)``.
        Every block is clipped to the simulated half and completed
        across each plane, so the file holds the whole model.

    Returns
    -------
    list of dict
        The material table (``{"name", "rgba"}`` per entry) the block
        colouring refers to.
    """
    import vtk  # noqa: PLC0415
    from vtk.util import numpy_support as ns  # noqa: PLC0415

    shapes = list(geometry)
    table, indices = _material_table(
        [s.material for s in shapes], [getattr(s, "color", None) for s in shapes]
    )

    # DD-120: tessellate at the model scale, convert points to meters.
    geo_scale = 1.0
    if shapes and all(hasattr(s, "_analytic_bbox") for s in shapes):
        from magnelio.geo._scaling import model_scale  # noqa: PLC0415

        geo_scale = model_scale(shapes)

    mb = vtk.vtkMultiBlockDataSet()
    mb.SetNumberOfBlocks(len(shapes))
    used_names: set[str] = set()
    for i, shape in enumerate(shapes):
        name = getattr(shape, "name", None) or f"shape_{i}"
        label = name
        n = 2
        while label in used_names:
            label = f"{name}_{n}"
            n += 1
        used_names.add(label)
        mb.GetMetaData(i).Set(vtk.vtkCompositeDataSet.NAME(), label)

        tess = _tessellate_shape(
            shape._occ_shape(geo_scale),
            None if deflection is None else deflection * geo_scale,
        )
        if tess is None:
            continue
        tess_points, tess_tris = tess
        pd = _polydata(tess_points / geo_scale, tess_tris)
        mat_idx = np.full(pd.GetNumberOfCells(), indices[i], dtype=np.int32)
        arr = ns.numpy_to_vtk(mat_idx, deep=True)
        arr.SetName("MaterialIndex")
        pd.GetCellData().AddArray(arr)
        for plane in mirrors or ():
            axis = "xyz".index(plane[0])
            pd = _half_and_mirror(pd, axis, float(plane[1]), bool(plane[2]))
        name_arr = vtk.vtkStringArray()
        name_arr.SetName("MaterialName")
        name_arr.InsertNextValue(table[indices[i]]["name"])
        pd.GetFieldData().AddArray(name_arr)
        mb.SetBlock(i, pd)

    writer = vtk.vtkXMLMultiBlockDataWriter()
    writer.SetFileName(str(path))
    writer.SetInputData(mb)
    writer.Write()
    return table


