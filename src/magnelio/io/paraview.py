def write_paraview_script(script_path: str | Path, config: dict) -> Path:
    """Write the generated ``paraview.simple`` pipeline script."""
    script_path = Path(script_path)
    payload = json.dumps(config)
    script_path.write_text(
        _SCRIPT_HEADER
        + f"CONFIG = json.loads({payload!r})\n"
        + f"VERSION_MARKER = {_VERSION_MARKER!r}\n"
        + f"FIELD_SCRIPT = {_FIELD_SCRIPT!r}\n"
        + f"INFO_SCRIPT = {_INFO_SCRIPT!r}\n"
        + f"UPDATE_SCRIPT = {_UPDATE_SCRIPT!r}\n"
        + _SCRIPT_BODY,
        encoding="utf-8",
    )
    return script_path


def resolve_pvpython(pvpython=None) -> list[str] | None:
    """How to start the ``pvpython`` a bake should use, or ``None``.

    Returns the command as a list, ready to be extended with the bake's
    own arguments.  In order: the argument, ``MAGNELIO_PVPYTHON``, then
    the first ``pvpython`` on ``PATH``.  The choice matters because the
    state file a bake writes is only good for the ParaView that wrote it
    — a machine carrying a distribution build beside a downloaded one
    bakes for whichever comes first, which need not be the one that
    opens the session (DD-265).

    Parameters
    ----------
    pvpython : str or Path or sequence of str, optional
        A path to an interpreter, or the command that launches one —
        a sandboxed or containerised ParaView is reached through its
        runner rather than through a file on ``PATH``, e.g.
        ``"flatpak run --command=pvpython org.paraview.ParaView"``.  A
        string is split on whitespace, so pass a sequence when a path
        contains spaces.
    """
    import os  # noqa: PLC0415
    import shlex  # noqa: PLC0415

    named = pvpython or os.environ.get("MAGNELIO_PVPYTHON")
    if not named:
        found = shutil.which("pvpython")
        return [found] if found else None
    parts = [str(named)] if isinstance(named, Path) else list(named)
    if isinstance(named, str):
        parts = shlex.split(named)
    if not parts:
        return None
    resolved = _which(parts[0])
    if resolved is None and len(parts) == 1 and parts[0].strip() != parts[0].split()[0]:
        # One token carrying whitespace and naming nothing: a command
        # someone quoted as a whole.  IPython's ``%set_env VAR="a b c"``
        # keeps the quotes in the value, and shlex then reads the lot as
        # a single argument.  A real path with spaces resolved above and
        # never reaches here.
        parts = parts[0].split()
        resolved = _which(parts[0])
    return None if resolved is None else [resolved, *parts[1:]]


def _which(name: str) -> str | None:
    """*name* as an executable path, or ``None``."""
    return shutil.which(name) or (name if Path(name).is_file() else None)


def _stamp_version(script_path: Path, version: str) -> None:
    """Write the baking ParaView's version into the script's header."""
    # GetParaViewSourceVersion() answers "paraview version 6.1.0".
    version = version.replace("paraview version", "").strip() or version
    try:
        text = script_path.read_text(encoding="utf-8")
        script_path.write_text(
            text.replace(_STAMP_PREFIX + _STAMP_NONE, _STAMP_PREFIX + version, 1),
            encoding="utf-8",
        )
    except OSError:  # pragma: no cover - the script was just written
        pass


def bake_pvsm(
    script_path: str | Path,
    pvsm_path: str | Path,
    timeout: float = 300.0,
    pvpython=None,
) -> bool:
    """Bake the pipeline script into a ``.pvsm`` state file via ``pvpython``.

    Returns ``False`` (without raising) when no ``pvpython`` is found or
    the bake fails — the script remains the portable fallback.  On
    success the baking ParaView's version is written into the script's
    header, because the state file is bound to it.
    ``MAGNELIO_PVSM_BAKE=0`` disables the bake globally (the test suite
    pins this: a ``pvpython`` subprocess per streamed run would dominate
    its runtime); ``MAGNELIO_PVPYTHON`` names the interpreter, or the
    command that launches one (:func:`resolve_pvpython`).
    """
    import os  # noqa: PLC0415

    if os.environ.get("MAGNELIO_PVSM_BAKE", "1") == "0":
        return False
    cmd = resolve_pvpython(pvpython)
    if cmd is None:
        # Silence here is what makes a mistyped setting expensive: the
        # call returns, the state file is simply absent, and nothing
        # says which of the two it was.
        named = pvpython or os.environ.get("MAGNELIO_PVPYTHON")
        if named:
            warnings.warn(
                f"no ParaView state file was baked: {named!r} is not an executable, so "
                f"nothing could run the session script.  Note that a value quoted as a "
                f"whole is one argument, not a command — IPython's %set_env keeps those "
                f"quotes.  The session opens without a state file: "
                f"paraview --script=paraview_open.py",
                UserWarning,
                stacklevel=4,
            )
        else:
            warnings.warn(
                "no ParaView state file was baked: no 'pvpython' on PATH.  Name one in "
                "MAGNELIO_PVPYTHON or in export_paraview(pvpython=...) — a path, or the "
                "command that launches one, e.g. "
                "flatpak run --command=pvpython org.paraview.ParaView.  The session opens "
                "without a state file: paraview --script=paraview_open.py",
                UserWarning,
                stacklevel=4,
            )
        return False
    pvsm_path = Path(pvsm_path)
    cmd = [
        *cmd,
        "--force-offscreen-rendering",
        str(script_path),
        "--save-state",
        str(pvsm_path),
    ]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return False
    baked = proc.returncode == 0 and pvsm_path.exists()
    if not baked:
        tail = (proc.stderr or proc.stdout or "").strip().splitlines()[-3:]
        warnings.warn(
            f"no ParaView state file was baked: {' '.join(cmd[: len(cmd) - 4])} exited "
            f"with {proc.returncode} or wrote nothing.  The session opens without one: "
            f"paraview --script=paraview_open.py" + ("\n" + "\n".join(tail) if tail else ""),
            UserWarning,
            stacklevel=4,
        )
    if baked:
        for line in (proc.stdout or "").splitlines():
            if line.startswith(_VERSION_MARKER):
                _stamp_version(Path(script_path), line.split(maxsplit=1)[-1].strip())
                break
    return baked


def _ensure_geometry_vtm(project, mirrors=None) -> None:
    """Tessellate the stored geometry into ``geometry.vtm`` if it is missing.

    The exact ``geometry.brep`` is what the store writes; the multiblock
    mesh ParaView reads is made here, on the first export, whole — the
    solids completed across the declared symmetry planes (DD-265).  The
    planes it was built for are recorded beside it, so a file written
    before the completion (or for other planes) is made again rather
    than shown as a half model.  Best-effort: a tessellation failure (or
    a build without the CAD kernel) warns and the session goes on
    without the solids.
    """
    path = project.path / "geometry.vtm"
    stamp = project.path / "geometry.vtm.json"
    mirrors = [list(m) for m in (mirrors or ())]
    if not (project.path / "geometry.brep").exists():
        return
    if path.exists():
        try:
            written = json.loads(stamp.read_text(encoding="utf-8"))["mirrors"]
        except (OSError, ValueError, KeyError):
            # No stamp: a file from before the completion existed, which
            # is the whole model already when nothing is mirrored.
            written = [] if not mirrors else None
        if written == mirrors:
            return
    try:
        with warnings.catch_warnings():
            # The geometry reader notes thin wires it cannot rebuild;
            # they carry no solid to tessellate anyway.
            warnings.simplefilter("ignore")
            solids = list(project.geometry)
        if solids:
            export_vtm(path, solids, mirrors=mirrors)
            stamp.write_text(json.dumps({"mirrors": mirrors}), encoding="utf-8")
    except Exception as exc:  # viz-only; the field export goes on
        warnings.warn(
            f"geometry.vtm could not be written (the ParaView session shows no solids): {exc}",
            UserWarning,
            stacklevel=2,
        )


def _geometry_config(project_path: Path, rel: str) -> tuple[str | None, list[dict]]:
    """``(relative geometry.vtm path, material table)`` for a session.

    *rel* is the path from the session script's own directory, which
    differs between a run session (two levels down) and the project-level
    eigenmode session (alongside).
    """
    from magnelio.io.project import _material_from_dict  # noqa: PLC0415

    if not (project_path / "geometry.vtm").exists():
        return None, []
    gj_path = project_path / "geometry.json"
    if not gj_path.exists():
        return rel, []
    gj = json.loads(gj_path.read_text(encoding="utf-8"))
    kinds = gj.get("kinds", ["solid"] * len(gj["materials"]))
    file_colors = gj.get("colors") or [None] * len(gj["materials"])
    pairs = [
        (_material_from_dict(d), c)
        for d, c, kind in zip(gj["materials"], file_colors, kinds)
        if kind != "wire"
    ]
    materials, _ = _material_table([m for m, _ in pairs], [c for _, c in pairs])
    return rel, materials


def _symmetry_config(project) -> list:
    """Declared symmetry planes as ``[[axis, wall_m, at_low, kind], ...]``.

    Read from the stored mesh (DD-154); the wall coordinate reuses the
    monitor mirror resolution (PEC on the outermost grid line, PMC half
    the boundary cell outside — the physical mirror plane).  The wall
    *kind* travels with it because it decides the sign every field
    component picks up across the plane.  Empty when the project stores
    no mesh or the mesh declares no symmetry.
    """
    from magnelio.monitors.base import resolve_mirrors, resolve_region  # noqa: PLC0415

    try:
        mesh = project.mesh
    except Exception:  # noqa: BLE001 — no stored mesh
        return []
    if mesh is None:
        return []
    mirrors = resolve_mirrors(resolve_region(None, mesh.grid), mesh)
    return [["xyz"[m.axis], m.wall, m.at_low, m.kind] for m in mirrors]


def export_eigenmode_visualization(
    project_path: str | Path,
    *,
    glyph_percentile: float = 98.0,
    bake_state: bool = True,
    pvpython: str | Path | None = None,
) -> dict:
    """Generate the ready-to-open ParaView session for stored eigenmodes.

    The eigenmode counterpart of :func:`export_run_visualization`.
    Eigenmodes belong to the project rather than to a run (they have no
    excitation and no time axis), so the artefacts sit in the project
    directory itself: ``paraview/eigenmodes/mode_*.vtr`` plus
    ``paraview/eigenmodes.pvd``, the pipeline script
    ``paraview_open.py`` and — when *bake_state* and ``pvpython`` is
    available — ``paraview.pvsm``.

    Stepping the ParaView time axis steps through the **modes**; each
    file carries its eigenfrequency as field data.  Fields are
    peak-normalised per mode (an eigenvector has no absolute
    amplitude), with the divisors stored alongside.

    Parameters
    ----------
    project_path : str or Path
        The project directory; must contain ``eigenmodes.h5``.
    glyph_percentile : float, default 98.0
        Percentile of ``|E|`` used as the glyph magnitude clip cap.
    bake_state : bool, default True
        Attempt the ``pvpython`` state bake.
    pvpython : str or Path or sequence of str, optional
        The ``pvpython`` that bakes the state file, when the machine
        carries more than one ParaView — a path, or the command that
        launches one (:func:`resolve_pvpython`).  Default:
        ``MAGNELIO_PVPYTHON``, else the first on ``PATH``.  The state is
        only good for the version that wrote it, so name the one that
        will open it.

    Returns
    -------
    dict
        Written artefact paths (``script``, ``state`` or ``None``,
        ``monitors``); empty when the project stores no eigenmodes.
    """
    from magnelio.io.project import Project  # noqa: PLC0415

    project = Project(project_path)
    if not (project.path / "eigenmodes.h5").exists():
        return {}
    mirrors = _symmetry_config(project)
    _ensure_geometry_vtm(project, mirrors)

    pv_dir = project.path / "paraview"
    pv_dir.mkdir(exist_ok=True)
    spec = _export_eigenmodes(project.path, pv_dir, project.grid, glyph_percentile)
    if spec is None:
        return {}

    geometry_rel, materials = _geometry_config(project.path, "geometry.vtm")
    _prepare_mirroring([spec], mirrors)
    config = {
        "geometry": geometry_rel,
        "materials": materials,
        "monitors": [spec],
        "symmetry": mirrors,
    }
    script = write_paraview_script(project.path / "paraview_open.py", config)
    state = project.path / "paraview.pvsm"
    baked = bake_state and bake_pvsm(script, state, pvpython=pvpython)
    return {
        "script": script,
        "state": state if baked else None,
        "monitors": ["eigenmodes"],
    }


