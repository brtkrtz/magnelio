def _pick_vector(components) -> tuple[str, list[str]] | None:
    """The preferred complete field triple among *components* (E over H)."""
    comps = set(components)
    for field in ("E", "H"):
        triple = [f"{field}{ax}" for ax in "xyz"]
        if all(c in comps for c in triple):
            return field, triple
    return None


def _mirror_signature(array_name: str) -> tuple[str, int | None] | None:
    """``(field, component axis)`` of an exported field array, or ``None``.

    ``Ex`` and ``Hz_im`` name a single component, ``E`` and ``E_re`` the
    3-component vector (component ``None``).  Magnitudes and anything
    unrecognised give ``None``: they are even across every mirror and
    need no correction.
    """
    stem = array_name
    for suffix in ("_re", "_im"):
        if stem.endswith(suffix):
            stem = stem[: -len(suffix)]
            break
    if stem in ("E", "H"):
        return stem, None
    if len(stem) == 2 and stem[0] in ("E", "H") and stem[1] in _COMP_AXES:
        return stem[0], _COMP_AXES[stem[1]]
    return None


def _mirror_factor(field: str, comp: int | None, mirror_axis: int, kind: str) -> float:
    """Sign the renderer's reflection filter still owes a field array.

    The filter transforms every 3-component array as a polar vector: it
    negates the component along the mirror axis and leaves the other two.
    That is the entire continuation exactly when the normal component is
    the odd one — for the other pairing every component is off by a
    global minus, which is what a vector gets back here.  Single
    components the filter never touches, so they carry their
    continuation factor in full.
    """
    from magnelio.post._symmetry import mirror_sign  # noqa: PLC0415

    if comp is None:
        return -mirror_sign(field, mirror_axis, mirror_axis, kind)
    return mirror_sign(field, comp, mirror_axis, kind)


def _mirror_fixes(array_names, mirrors) -> list[list]:
    """Per mirror plane, the ``[name, factor]`` pairs needing correction.

    Arrays the filter already continues correctly are left out, so a
    plane that needs nothing produces an empty list and stays a single
    reflection rather than a reflect/negate/join branch.
    """
    fixes = []
    for axis, _wall, _at_low, kind in mirrors:
        mirror_axis = _COMP_AXES[axis]
        plane = []
        for name in array_names:
            signature = _mirror_signature(name)
            if signature is None:
                continue
            factor = _mirror_factor(signature[0], signature[1], mirror_axis, kind)
            if factor < 0.0:
                plane.append([name, factor])
        fixes.append(plane)
    return fixes


def _prepare_mirroring(monitors, mirrors) -> None:
    """Resolve each monitor spec against the declared mirror planes.

    Two edits, both in place.  The sign corrections replace the raw array
    listing, and a monitor collapsed onto a mirrored axis gets its second
    sampling layer: mirroring turns its single cell layer into two, and a
    lattice of one would sample the seam between them instead.

    The lattice is deliberately *not* widened otherwise.  Its spacing is
    sized for a target arrow count in the displayed picture, and the
    displayed picture is the mirrored one — keeping the dimensions puts
    that target on the full model rather than on each half.
    """
    for spec in monitors:
        spec["mirror_fix"] = _mirror_fixes(spec.pop("field_arrays", []), mirrors)
        for axis, _wall, _at_low, _kind in mirrors:
            index = _COMP_AXES[axis]
            for key in ("resample_dims", "resample_dims_volume"):
                dims = spec.get(key)
                if dims and dims[index] == 1:
                    dims[index] = 2


def _sample_steps(n: int, k: int = _CAP_TIME_SAMPLES) -> list[int]:
    return sorted(set(np.linspace(0, n - 1, min(k, n)).astype(int).tolist()))


def _spatial_stride(shape) -> tuple[slice, ...]:
    total = int(np.prod(shape))
    if total <= _CAP_MAX_SAMPLES:
        return (slice(None),) * len(shape)
    s = int(np.ceil((total / _CAP_MAX_SAMPLES) ** (1.0 / len(shape))))
    return tuple(slice(None, None, s) for _ in shape)


def _magnitude_stats(component_steps, percentile: float) -> tuple[float, float]:
    """Glyph clip cap and length reference from sampled ``|v|``.

    ``component_steps`` yields, per sampled step, the list of component
    arrays (already spatially subsampled).  Two *different* numbers come
    out of the pooled magnitudes, and conflating them makes the glyphs
    unusable (DD-115 follow-up):

    * **cap** — the high percentile at which arrow length saturates, so
      edge singularities keep their direction without dictating the
      scale.  Taken over all samples.
    * **reference** — the magnitude that maps to the full arrow length.
      Taken over the *field-carrying* cells only (above 1 % of the
      maximum): a monitor spanning the whole domain is typically half
      zeros — PEC interiors and quiet volume — and a percentile over
      those puts the reference next to the maximum, which renders the
      typical arrow sub-millimetre.
    """
    chunks = []
    for comps in component_steps:
        m2 = None
        for a in comps:
            a = np.abs(np.asarray(a, dtype=np.complex128 if np.iscomplexobj(a) else np.float64))
            m2 = a * a if m2 is None else m2 + a * a
        chunks.append(np.sqrt(np.real(m2)).ravel())
    vals = np.concatenate(chunks) if chunks else np.zeros(0)
    if vals.size == 0 or not np.any(vals > 0.0):
        return 0.0, 1.0
    cap = float(np.percentile(vals, percentile))
    live = vals[vals > _LIVE_CELL_FRACTION * vals.max()]
    ref = float(np.percentile(live, _REFERENCE_PERCENTILE)) if live.size else cap
    if cap <= 0.0:
        return 0.0, 1.0
    return cap, _length_exponent(ref, cap)


def _length_exponent(reference: float, cap: float) -> float:
    """Exponent mapping *reference* to a fixed fraction of the full length.

    The glyph length factor is ``(m/cap) ** exponent``.  Solving
    ``(reference/cap) ** e == _REFERENCE_LENGTH_FRACTION`` puts the
    typical field-carrying magnitude at a visible length while the cap
    still maps to exactly 1, so the longest arrow stays bounded.  A
    linear map falls out (exponent 1) when the reference already sits at
    that fraction; heavier-tailed distributions compress harder.
    """
    lo, hi = _EXPONENT_LIMITS
    if not 0.0 < reference < cap:
        return hi
    e = float(np.log(_REFERENCE_LENGTH_FRACTION) / np.log(reference / cap))
    return float(min(max(e, lo), hi))


def _monitor_geometry(node_x, node_y, node_z) -> dict:
    """Slice-plane spec derived from a monitor's node coordinates."""
    nodes = [np.asarray(node_x), np.asarray(node_y), np.asarray(node_z)]
    ext = [float(a[-1] - a[0]) for a in nodes]
    center = [float(0.5 * (a[0] + a[-1])) for a in nodes]
    ncells = [len(a) - 1 for a in nodes]
    axes = ["x", "y", "z"]
    degenerate = [ax for ax, n in zip(axes, ncells) if n <= 1]
    diag = float(np.sqrt(sum(e * e for e in ext)))
    # A single-cell axis is degenerate for the lattice even though it has
    # a physical thickness: a plane monitor must resample to one layer,
    # not to several through a thickness that carries no second sample.
    lat_ext = [0.0 if n <= 1 else e for e, n in zip(ext, ncells)]
    spec = {
        "center": center,
        "slice_axes": [],
        "default_axis": None,
        "planar_normal": None,
        "resample_dims": _lattice_dims(lat_ext, _section_step(lat_ext)),
        "resample_dims_volume": None,
        "l_ref": max(diag * _GLYPH_LENGTH_FRACTION, 1e-12),
    }
    if not degenerate:
        spec["slice_axes"] = axes
        # Cutting normal to the shortest extent exposes the largest
        # section area — the natural first view of a 3D monitor.
        spec["default_axis"] = axes[int(np.argmin(ext))]
        step = _volume_step(lat_ext)
        if step:
            spec["resample_dims_volume"] = _lattice_dims(lat_ext, step)
    elif len(degenerate) == 1:
        spec["planar_normal"] = degenerate[0]
    return spec


def _lattice_dims(extents, step: float) -> list[int]:
    """Grid dimensions for *step* spacing; degenerate axes collapse to 1.

    One spacing for every axis, deliberately: a fixed sample count per
    axis would make the spacing directional on an elongated region —
    exactly the bias that placing arrows on the computational grid
    produced in the first place.
    """
    return [
        1 if e <= 0.0 else int(min(max(round(e / step) + 1, 2), _RESAMPLE_MAX_PER_AXIS))
        for e in extents
    ]


def _section_step(extents) -> float:
    """Lattice spacing giving ~``_ARROWS_PER_SECTION`` arrows in a cut.

    Sized from the *largest* section through the region (the plane
    spanning the two longest extents, which is also the default cut), so
    that view lands on the target and the narrower cuts scale down with
    their own area rather than being starved.
    """
    live = sorted((float(e) for e in extents if e > 0.0), reverse=True)
    if len(live) < 2:
        return live[0] / 8.0 if live else 1.0
    return float(np.sqrt(live[0] * live[1] / _ARROWS_PER_SECTION))


def _volume_step(extents) -> float | None:
    """Lattice spacing for a bounded arrow count in the volume view."""
    live = [float(e) for e in extents if e > 0.0]
    if len(live) < 3:
        return None
    return float((live[0] * live[1] * live[2] / _RESAMPLE_VOLUME_POINTS) ** (1.0 / 3.0))


def _export_time_monitor(run_dir: Path, pv_dir: Path, name: str, percentile: float):
    """Per-monitor XDMF (over ``results.h5``) + pipeline spec, or ``None``."""
    import h5py  # noqa: PLC0415

    from magnelio.io.xdmf import _vector_groups, write_run_xdmf  # noqa: PLC0415

    with h5py.File(run_dir / "results.h5", "r", swmr=True) as f:
        mg = f["monitors"][name]
        components = json.loads(mg.attrs["components"])
        times = mg["times"][()]
        n = int(times.shape[0])
        if n == 0:
            return None
        gx, gy, gz = mg["grid_x"][()], mg["grid_y"][()], mg["grid_z"][()]
        vec = _pick_vector(components)
        cap, exponent = 0.0, 1.0
        if vec is not None:
            sl = _spatial_stride(mg[vec[1][0]].shape[1:])

            def steps():
                for ti in _sample_steps(n):
                    yield [mg[c][ti][sl] for c in vec[1]]

            cap, exponent = _magnitude_stats(steps(), percentile)

    safe = _sanitize(name)
    write_run_xdmf(
        pv_dir / f"{safe}.xdmf",
        "../results.h5",
        [
            {
                "name": name,
                "n": n,
                "nx": len(gx) - 1,
                "ny": len(gy) - 1,
                "nz": len(gz) - 1,
                "components": components,
                "times": times,
            }
        ],
    )

    spec = _monitor_geometry(gx, gy, gz)
    spec.update(
        {
            "name": name,
            "kind": "time",
            "data": f"paraview/{safe}.xdmf",
            "reader": "xdmf",
            "glyph": None,
            "field_arrays": list(components) + [n for n, _ds in _vector_groups(components)],
        }
    )
    if vec is not None and cap > 0.0:
        spec["glyph"] = {
            "arrays": [vec[0]],
            "cap": cap,
            "exponent": exponent,
            "length": spec["l_ref"],
            "threshold": cap * _VOLUME_THRESHOLD_FRACTION,
        }
    return spec


def _freq_region_nodes(corners_arr, grid):
    """Node coordinates for a frequency monitor's stored region.

    ``fields_freq.h5`` stores cell-centre axes; the ``.vtr`` cells need
    node coordinates, recovered exactly by re-resolving the stored
    corners against the stored mesh grid (deterministic, DD-104).
    """
    from magnelio.monitors.base import _corners_from_array, resolve_region  # noqa: PLC0415

    region = resolve_region(_corners_from_array(corners_arr), grid)
    return (
        grid.x[region.ix.start : region.ix.stop + 1],
        grid.y[region.iy.start : region.iy.stop + 1],
        grid.z[region.iz.start : region.iz.stop + 1],
    )


def _freq_vtr_grid(node_x, node_y, node_z):
    import vtk  # noqa: PLC0415
    from vtk.util import numpy_support as ns  # noqa: PLC0415

    rg = vtk.vtkRectilinearGrid()
    rg.SetDimensions(len(node_x), len(node_y), len(node_z))
    setters = (rg.SetXCoordinates, rg.SetYCoordinates, rg.SetZCoordinates)
    for axis, nodes, setter in zip("xyz", (node_x, node_y, node_z), setters):
        arr = ns.numpy_to_vtk(np.asarray(nodes, dtype=np.float64), deep=True)
        # Unnamed VTK arrays are written as "Array 0x<address>", which
        # makes the file differ between processes for identical data.
        # Naming them keeps the export byte-reproducible.
        arr.SetName(f"{axis}_nodes")
        setter(arr)
    return rg


def _flat_cells(a: np.ndarray) -> np.ndarray:
    """Monitor-native ``(nx, ny, nz)`` -> VTK cell order (x fastest)."""
    return np.ascontiguousarray(a.transpose(2, 1, 0)).ravel()


def _run_source_spectrum(run_dir: Path, freqs: np.ndarray):
    """The run's excitation transformed at *freqs*, or ``None`` if absent.

    Reads through the store's own run reader rather than reaching into
    ``results.h5``: that reader truncates every stream to their common
    prefix, so a run cut short yields the same waveform here as it does
    through :class:`~magnelio.io.project.Project` — and therefore the
    same spectrum, to the last bit.
    """
    from magnelio.io.project import _read_run_results  # noqa: PLC0415
    from magnelio.monitors._dft import source_spectrum  # noqa: PLC0415

    try:
        sig = _read_run_results(run_dir)["reference"]
    except (OSError, KeyError):
        return None
    return source_spectrum(sig.values, sig.dt, freqs)


def _export_freq_monitor(run_dir: Path, pv_dir: Path, name: str, grid, percentile: float):
    """``.vtr``-per-frequency series + ``.pvd`` collection + pipeline spec."""
    import h5py  # noqa: PLC0415
    import vtk  # noqa: PLC0415
    from vtk.util import numpy_support as ns  # noqa: PLC0415

    from magnelio.monitors._dft import divide_by_spectrum  # noqa: PLC0415

    with h5py.File(run_dir / "fields_freq.h5", "r") as f:
        g = f[name]
        components = json.loads(g.attrs["components"])
        freqs = np.asarray(g["freqs"][()], dtype=float)
        corners = g["corners"][()]
        bins = {c: g["bins"][c][()] for c in components}
    if freqs.size == 0 or not components:
        return None
    # Ship the same quantity the monitor's own ``.data`` reports — fields
    # per 1 W CW — so a value read off the renderer means what a value
    # read in Python means.  A run without a stored excitation (none in
    # practice) exports the raw bins rather than nothing.
    spectrum = _run_source_spectrum(run_dir, freqs)
    if spectrum is not None:
        bins = {c: divide_by_spectrum(v, spectrum) for c, v in bins.items()}

    node_x, node_y, node_z = _freq_region_nodes(corners, grid)
    first = bins[components[0]]
    if first.shape[1:] != (len(node_x) - 1, len(node_y) - 1, len(node_z) - 1):
        return None  # stored grid no longer matches the bins; skip quietly

    safe = _sanitize(name)
    mon_dir = pv_dir / safe
    mon_dir.mkdir(parents=True, exist_ok=True)

    vec = _pick_vector(components)
    entries = []
    for fi, f_val in enumerate(freqs):
        rg = _freq_vtr_grid(node_x, node_y, node_z)
        cd = rg.GetCellData()

        def add(name_, data):
            arr = ns.numpy_to_vtk(np.ascontiguousarray(data, dtype=np.float64), deep=True)
            arr.SetName(name_)
            cd.AddArray(arr)

        for c in components:
            a = bins[c][fi]
            add(f"{c}_re", _flat_cells(a.real))
            add(f"{c}_im", _flat_cells(a.imag))
        if vec is not None:
            field, triple = vec
            re = np.stack([_flat_cells(bins[c][fi].real) for c in triple], axis=-1)
            im = np.stack([_flat_cells(bins[c][fi].imag) for c in triple], axis=-1)
            add(f"{field}_re", re)
            add(f"{field}_im", im)
            add(f"|{field}|", np.sqrt(np.sum(re * re + im * im, axis=-1)))

        writer = vtk.vtkXMLRectilinearGridWriter()
        rel = f"{safe}/f_{fi:04d}.vtr"
        writer.SetFileName(str(pv_dir / rel))
        writer.SetInputData(rg)
        writer.Write()
        entries.append((f_val, rel))

    pvd_lines = [
        '<?xml version="1.0"?>',
        '<VTKFile type="Collection" version="0.1">',
        "  <Collection>",
    ]
    pvd_lines += [
        f'    <DataSet timestep="{f_val:.9e}" part="0" file="{rel}"/>' for f_val, rel in entries
    ]
    pvd_lines += ["  </Collection>", "</VTKFile>", ""]
    (pv_dir / f"{safe}.pvd").write_text("\n".join(pvd_lines), encoding="utf-8")

    field_arrays = [f"{c}_{part}" for c in components for part in ("re", "im")]
    if vec is not None:
        field_arrays += [f"{vec[0]}_re", f"{vec[0]}_im"]
    spec = _monitor_geometry(node_x, node_y, node_z)
    spec.update(
        {
            "name": name,
            "kind": "freq",
            "data": f"paraview/{safe}.pvd",
            "reader": "pvd",
            "glyph": None,
            "field_arrays": field_arrays,
        }
    )
    if vec is not None:
        field, triple = vec
        sl = _spatial_stride(first.shape[1:])

        def steps():
            for fi in _sample_steps(len(freqs)):
                yield [bins[c][fi][sl] for c in triple]

        cap, exponent = _magnitude_stats(steps(), percentile)
        if cap > 0.0:
            # Real and imaginary part each get their own glyph set: they
            # are the field at phase 0 and at phase −90°, and together
            # they span the full ellipse — where one nearly vanishes the
            # other carries the field, so offering only the real part
            # hides half the picture.  Both share the cap and reference
            # from the complex magnitude, which bounds either phase.
            spec["glyph"] = {
                "arrays": [f"{field}_re", f"{field}_im"],
                "cap": cap,
                "exponent": exponent,
                "length": spec["l_ref"],
                "threshold": cap * _VOLUME_THRESHOLD_FRACTION,
            }
    return spec


def _eigenmode_fields(mode_arrays: dict, grid):
    """One stored eigenmode as cell-centred E and H, peak-normalised.

    The stored arrays are the solver's FIT grid quantities (edge
    voltages / face currents), so they go through the same
    ``_interp_to_cell_centres`` conversion the field monitors use
    (DD-085).  An eigenvector carries no absolute amplitude — the
    solver's own scaling ran to 1e8 on the tutorial-13 cavity, which
    reads as V/m and is not — so each field is divided by its own peak
    magnitude.  The two divisors are returned with the fields: they are
    the only thing lost, and writing them into the file keeps the
    normalisation reversible.
    """
    from magnelio._fields.field_arrays import FieldState  # noqa: PLC0415
    from magnelio.monitors.base import _interp_to_cell_centres  # noqa: PLC0415

    state = FieldState(**mode_arrays)
    cells = _interp_to_cell_centres(
        state,
        ["Ex", "Ey", "Ez", "Hx", "Hy", "Hz"],
        slice(0, grid.Nx),
        slice(0, grid.Ny),
        slice(0, grid.Nz),
        grid,
    )
    scales = {}
    for field in ("E", "H"):
        triple = [cells[f"{field}{ax}"] for ax in "xyz"]
        peak = float(np.sqrt(sum(np.asarray(c, dtype=float) ** 2 for c in triple)).max())
        scales[field] = peak if peak > 0.0 else 1.0
        for ax in "xyz":
            cells[f"{field}{ax}"] = np.asarray(cells[f"{field}{ax}"], dtype=float) / scales[field]
    return cells, scales


def _export_eigenmodes(project_path: Path, pv_dir: Path, grid, percentile: float):
    """``.vtr``-per-mode series + ``.pvd`` collection + pipeline spec.

    The ParaView axis carries the **mode index**, not the eigenfrequency:
    degenerate pairs share a frequency to the last digit (they are the
    rule, not the exception, in any symmetric cavity), and two datasets
    at one timestep hide each other.  The frequency travels as field
    data instead, so it is still displayed and still exact.
    """
    import h5py  # noqa: PLC0415
    import vtk  # noqa: PLC0415
    from vtk.util import numpy_support as ns  # noqa: PLC0415

    src = project_path / "eigenmodes.h5"
    if not src.exists():
        return None
    comps = ["Ex", "Ey", "Ez", "Hx", "Hy", "Hz"]
    with h5py.File(src, "r") as f:
        freqs = np.asarray(f["frequencies"][()], dtype=float)
        raw = [{c: f[f"mode_{i:03d}"][c][()] for c in comps} for i in range(freqs.size)]
    if freqs.size == 0:
        return None

    node_x, node_y, node_z = np.asarray(grid.x), np.asarray(grid.y), np.asarray(grid.z)
    mon_dir = pv_dir / "eigenmodes"
    mon_dir.mkdir(parents=True, exist_ok=True)

    entries = []
    cell_fields = []
    for i, mode_arrays in enumerate(raw):
        cells, scales = _eigenmode_fields(mode_arrays, grid)
        cell_fields.append(cells)
        rg = _freq_vtr_grid(node_x, node_y, node_z)
        cd = rg.GetCellData()
        for c in comps:
            arr = ns.numpy_to_vtk(_flat_cells(cells[c]), deep=True)
            arr.SetName(c)
            cd.AddArray(arr)
        for field in ("E", "H"):
            vec = np.stack([_flat_cells(cells[f"{field}{ax}"]) for ax in "xyz"], axis=-1)
            arr = ns.numpy_to_vtk(np.ascontiguousarray(vec), deep=True)
            arr.SetName(field)
            cd.AddArray(arr)
            mag = ns.numpy_to_vtk(np.sqrt(np.sum(vec * vec, axis=-1)), deep=True)
            mag.SetName(f"|{field}|")
            cd.AddArray(mag)
        # Provenance of this file, and the inverse of the normalisation.
        for label, value in (
            ("f_Hz", float(freqs[i])),
            ("mode_index", float(i)),
            ("E_peak_before_normalisation", scales["E"]),
            ("H_peak_before_normalisation", scales["H"]),
        ):
            fd = ns.numpy_to_vtk(np.array([value], dtype=np.float64), deep=True)
            fd.SetName(label)
            rg.GetFieldData().AddArray(fd)

        writer = vtk.vtkXMLRectilinearGridWriter()
        rel = f"eigenmodes/mode_{i:04d}.vtr"
        writer.SetFileName(str(pv_dir / rel))
        writer.SetInputData(rg)
        writer.Write()
        entries.append(rel)

    pvd_lines = [
        '<?xml version="1.0"?>',
        '<VTKFile type="Collection" version="0.1">',
        "  <Collection>",
    ]
    pvd_lines += [
        f'    <DataSet timestep="{i:d}" part="0" file="{rel}"/>' for i, rel in enumerate(entries)
    ]
    pvd_lines += ["  </Collection>", "</VTKFile>", ""]
    (pv_dir / "eigenmodes.pvd").write_text("\n".join(pvd_lines), encoding="utf-8")

    spec = _monitor_geometry(node_x, node_y, node_z)
    spec.update(
        {
            "name": "eigenmodes",
            "kind": "eigenmode",
            "data": "paraview/eigenmodes.pvd",
            "reader": "pvd",
            "glyph": None,
            "field_arrays": [*comps, "E", "H"],
        }
    )
    sl = _spatial_stride(cell_fields[0]["Ex"].shape)

    def steps():
        for i in _sample_steps(len(cell_fields)):
            yield [cell_fields[i][f"E{ax}"][sl] for ax in "xyz"]

    cap, exponent = _magnitude_stats(steps(), percentile)
    if cap > 0.0:
        # E only: the modes are peak-normalised per field, so an H glyph
        # set would be drawn at the same lengths from an unrelated
        # scaling — visually equal, physically incomparable.
        spec["glyph"] = {
            "arrays": ["E"],
            "cap": cap,
            "exponent": exponent,
            "length": spec["l_ref"],
            "threshold": cap * _VOLUME_THRESHOLD_FRACTION,
        }
    return spec


