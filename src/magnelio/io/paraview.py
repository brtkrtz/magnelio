"""ParaView export: multiblock geometry, frequency grids, session state.

Three layers:

1. :func:`export_vtm` — tessellate each solid into its own block of a VTK
   multiblock dataset (``geometry.vtm`` + ``geometry/*.vtp``).  Blocks carry
   the shape name and a ``MaterialIndex`` cell array; a categorical lookup
   table colours the blocks per material (colours from
   :func:`~magnelio.post._colors.material_color`, the same palette as the
   built-in 3D viewer).
2. Frequency-monitor export — the ``fields_freq.h5`` DFT bins as one
   rectilinear ``.vtr`` file per frequency plus a ``.pvd`` collection
   (frequency plays the role of the ParaView time axis).  Time monitors
   stay on the XDMF-over-``results.h5`` path — no data duplication.
   Eigenmodes take the same ``.vtr``/``.pvd`` shape one directory up
   (they belong to the project, not to a run), with the *mode index*
   on the ParaView axis — see :func:`export_eigenmode_visualization`.
3. :func:`export_run_visualization` — generates ``paraview_open.py``, a
   ``paraview.simple`` pipeline script (coloured geometry, per-monitor
   slice planes, normalised and magnitude-clipped field glyphs,
   plane-linked geometry clips) and, when ``pvpython`` is on the PATH,
   bakes it into a double-clickable ``paraview.pvsm`` state file.

Everything here is visualization-only: failures must never invalidate a
run, so the store calls into this module behind broad guards.
"""

